def btn(key: str) -> str:
    fun, plain = BUTTONS[key]
    return fun if _state["fun"] else plain


_state = {"fun": True, "address": ""}
_last: dict[str, str] = {}


def configure(fun: bool, address: str = "") -> None:
    _state["fun"] = fun
    _state["address"] = address


def address() -> str:
    return _state["address"] or random.choice(ADDRESSES)


def _lower_first(s: str) -> str:
    # «Господин ГИП» → «господин ГИП»
    return s[:1].lower() + s[1:]


def pick(key: str, **kw) -> str:
    if not _state["fun"] or key not in FUN:
        text = PLAIN.get(key, key)
    else:
        options = FUN[key]
        choices = [o for o in options if o != _last.get(key)] or options
        text = random.choice(choices)
        _last[key] = text
    if "{addr}" in text or "{Addr}" in text:
        a = address()
        kw.setdefault("Addr", a)
        kw.setdefault("addr", _lower_first(a))
    text = text.format(**kw)
    return text[:1].upper() + text[1:]
